def generate_code_file(file):
    '''
    This is the function that generates the code file
    The field of "index" is expected generated by your self,
    and it is used for distinct the different vulnerable code within the same CVE.
    '''
    output="your output dir"
    with open(file, 'r', encoding='utf-8') as f:
        data=json.load(f)
        for d in tqdm.tqdm(data):
            if d["lang"]=="C":
                with open(os.path.join(output,f'{d["cve_id"]}_{d["index"]}_before.c'), 'w', encoding='utf-8') as f:
                    f.write(d["func_before"])
                with open(os.path.join(output,f'{d["cve_id"]}_{d["index"]}_after.c'), 'w', encoding='utf-8') as f:
                    f.write(d["func_after"])
            elif d["lang"]=="CPP":
                with open(os.path.join(output,f'{d["cve_id"]}_{d["index"]}_before.cpp'), 'w', encoding='utf-8') as f:
                    f.write(d["func_before"])
                with open(os.path.join(output,f'{d["cve_id"]}_{d["index"]}_after.cpp'), 'w', encoding='utf-8') as f:
                    f.write(d["func_after"])
            else:
                print(d["cve_id"]+":"+str(d["index"]))

def get_joern_function_information_json(file):
    '''
    This function is used for get function information from joern.
    The result will be saved in json formate.
    '''
    input="the function files dir you select in 'generate_code_file' "+file
    output="the function information dir"+file.replace(".bin",".json")
    if os.path.exists(output):
        print(f"{output} already exists")
        return
    while True:
        query_response = requests.post(
            "http://localhost:8088/query",#change by your local url
            json={"query": f'''
            importCpg("{input}");
            cpg.method.l.toJson |> "{output}";
            cpg.close();
            var w=workspace.getActiveProject.get;
            workspace.removeProject(w.name);
            '''}
        )

        if query_response.status_code == 200:
            break
    if query_response.status_code == 200:

        response_data = query_response.json()
        if response_data['success']:
            uuid = response_data['uuid']
        else:
            return -1
    else:
        return -1
    uuid = response_data["uuid"]
    while True:
        result_response = requests.get(f"http://localhost:8088/result/{uuid}")
        if result_response.status_code != 200:
            return -2
        if result_response.json()['success']:
            break
        else:
            time.sleep(0.5)
def get_function_number(method_information,code):
    # Verify whether the code has empty body
    pre_brace=code.find('{')
    if pre_brace==-1:
        return -1
    last_brace=len(code)-1
    while last_brace>=0:
        if code[last_brace]=='}':
            break
        last_brace-=1
    if last_brace==-1:
        return -1
    content=code[pre_brace+1:last_brace].strip()
    if content=="":
        return -1

    #Verify whether the code contains more than one functions
    function_names=[]
    for m in method_information:
        if m['name'] in function_names:
            continue
        if m['name'].find('<') !=-1:
            continue
        if m["code"].find('<empty>') ==-1:
            function_names.append(m["name"])
    return len(function_names)
def get_filted_result_by_function_number():
    with open("your data file",'r',encoding='utf-8') as f:
        data=json.load(f)
        all_processed_data=[]
        all_failed_data=[]
        path="the output path in 'get_joern_function_information_json'"
        count = 0
        for d in tqdm.tqdm(data):
            if d['cve_id']=="":
                d['failed_reason']="None cve id"
                all_failed_data.append(d)
                continue
            file_before=f"{d['cve_id']}_{d['index']}_before.json"
            file_before=os.path.join(path,file_before)
            if not os.path.exists(file_before):
                d["failed_reason"]="failed to generate CPG"
                all_failed_data.append(d)
                continue
            method_information_before=json.load(open(file_before,'r',encoding='utf-8'))
            res_before=get_function_number(method_information_before,d['func_before'])
            file_after = f"{d['cve_id']}_{d['index']}_after.json"
            file_after = os.path.join(path, file_after)
            if not os.path.exists(file_after):
                d["failed_reason"]="failed to generate CPG"
                all_failed_data.append(d)
                continue
            method_information_after = json.load(open(file_after, 'r', encoding='utf-8'))
            res_after = get_function_number(method_information_after, d['func_after'])
            if res_before==res_after==1:
                all_processed_data.append(d.copy())
            else:
                d["failed_reason"]="Number of function"
                d["before_number"]=res_before
                d["after_number"]=res_after
                if res_before==-1 or res_after==-1:
                    count+=1
                all_failed_data.append(d)
        with open("your output file for selected data",'w',encoding='utf-8') as f:
            json.dump(all_processed_data,f,ensure_ascii=False,indent=4)
        with open("your output file for failed data",'w',encoding='utf-8') as f:
            json.dump(all_failed_data,f,ensure_ascii=False,indent=4)

